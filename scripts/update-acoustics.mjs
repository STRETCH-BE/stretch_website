#!/usr/bin/env node
// CLIENT PORTAL — ship a new build of the acoustic (reverberation-time)
// calculator. Reads acoustic-calculator.html from the repo root and writes
// TWO generated modules under src/lib/portal/:
//   acoustic-html.ts  — the file as base64, served only by /api/portal/acoustics
//   acoustic-data.ts  — the MATERIALEN / PANELEN / DOELEN tables lifted out of
//                       the file's <script>, so the API can recompute the
//                       headline results server-side without a second copy of
//                       the tables drifting away from the tool (the HTML stays
//                       the master; never edit acoustic-data.ts by hand).
// Usage: node scripts/update-acoustics.mjs   (see scripts/update-acoustics.md)
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const src = path.join(root, 'acoustic-calculator.html');
const html = fs.readFileSync(src, 'utf8');

// ---- base64 module ---------------------------------------------------------
const b64 = Buffer.from(html, 'utf8').toString('base64');
const chunks = b64.match(/.{1,4000}/g).map((c) => '  ' + JSON.stringify(c)).join(' +\n');
fs.writeFileSync(
  path.join(root, 'src/lib/portal/acoustic-html.ts'),
  '// CLIENT PORTAL — the acoustic (reverberation-time) calculator, a single-file\n' +
    '// HTML app embedded as base64 so it ships inside the server bundle and is ONLY\n' +
    '// served through the authenticated /api/portal/acoustics route (no pricing\n' +
    '// inside, but it is a portal feature — never put it in /public).\n' +
    '//\n' +
    '// GENERATED by scripts/update-acoustics.mjs from acoustic-calculator.html —\n' +
    '// do not edit by hand. The build includes the PORTAL BRIDGE (cloud-saved\n' +
    '// rooms, browser autosave, usage events) and the nl/en UI object.\n' +
    `export const ACOUSTIC_HTML_B64 =\n${chunks};\n`,
);

// ---- data tables -----------------------------------------------------------
// The arrays are plain JS object literals inside the file's IIFE. Evaluate
// just the literal (no DOM, no side effects) and freeze it as JSON.
function table(name) {
  const re = new RegExp(`var ${name} = \\[([\\s\\S]*?)\\n  \\];`);
  const m = re.exec(html);
  if (!m) throw new Error(`${name} table not found in acoustic-calculator.html`);
  // eslint-disable-next-line no-new-func
  return new Function(`return [${m[1]}];`)();
}
const materials = table('MATERIALEN').map(({ nr, naam, en, a }) => ({ nr, naam, en, a }));
const panels = table('PANELEN').map(({ nr, naam, a }) => ({ nr, naam, a }));
const targets = table('DOELEN').map(({ naam, en, t }) => ({ naam, en, t }));
for (const m of [...materials, ...panels]) {
  if (!Array.isArray(m.a) || m.a.length !== 6 || !m.a.every((x) => typeof x === 'number')) {
    throw new Error(`bad coefficient row: ${JSON.stringify(m)}`);
  }
}
const j = (v) => JSON.stringify(v, null, 2);
fs.writeFileSync(
  path.join(root, 'src/lib/portal/acoustic-data.ts'),
  '// CLIENT PORTAL — the acoustic calculator\'s material, absorber and target\n' +
    '// tables, lifted 1:1 out of acoustic-calculator.html so the API can derive\n' +
    '// the headline results of a saved room server-side (acoustic-summary.ts).\n' +
    '// The tool is the master copy of these numbers (transcribed from\n' +
    '// berekening-nagalmtijd-website-23.xlsx).\n' +
    '//\n' +
    '// GENERATED by scripts/update-acoustics.mjs — do not edit by hand.\n' +
    '\n' +
    '/** Octave bands, Hz — index into every `a` array. */\n' +
    'export const ACOUSTIC_BANDS = [125, 250, 500, 1000, 2000, 4000] as const;\n' +
    '/** The speech frequencies (500 / 1000 / 2000 Hz) — indices into ACOUSTIC_BANDS. */\n' +
    'export const ACOUSTIC_SPEECH = [2, 3, 4] as const;\n' +
    '\n' +
    'export type AcousticMaterial = { nr: number; naam: string; en: string; a: number[] };\n' +
    'export type AcousticPanel = { nr: number; naam: string; a: number[] };\n' +
    'export type AcousticTarget = { naam: string; en: string; t: number };\n' +
    '\n' +
    `export const ACOUSTIC_MATERIALS: AcousticMaterial[] = ${j(materials)};\n\n` +
    `export const ACOUSTIC_PANELS: AcousticPanel[] = ${j(panels)};\n\n` +
    `export const ACOUSTIC_TARGETS: AcousticTarget[] = ${j(targets)};\n`,
);

console.log(
  `acoustic-html.ts: ${Math.round(html.length / 1024)} KB source → ${Math.round(b64.length / 1024)} KB base64 · ` +
    `acoustic-data.ts: ${materials.length} materials, ${panels.length} panels, ${targets.length} room types`,
);
